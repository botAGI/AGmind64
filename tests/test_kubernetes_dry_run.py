def test_kubernetes_dry_run_artifact_records_manifest_digest_and_checksums(
    tmp_path: Path,
) -> None:
    from agmind.services.kubernetes_dry_run import (
        CommandResult,
        run_kubernetes_server_dry_run,
    )

    def fake_runner(command: tuple[str, ...], manifest: Path) -> CommandResult:
        return CommandResult(returncode=0, stdout="server dry-run ok", stderr="")

    report = run_kubernetes_server_dry_run(
        {"k3s-research": _kubernetes_target()},
        kubectl="kubectl",
        runner=fake_runner,
        artifact_dir=tmp_path,
    )

    manifest = tmp_path / "k3s-research.yaml"
    target_report = tmp_path / "k3s-research.dry-run.json"
    summary = tmp_path / "summary.json"
    checksums = tmp_path / "checksums.txt"
    manifest_bytes = manifest.read_bytes()
    summary_bytes = summary.read_bytes()
    target_report_bytes = target_report.read_bytes()

    assert report.ok is True
    assert checksums.exists()
    target_payload = json.loads(target_report_bytes)
    summary_payload = json.loads(summary_bytes)
    assert target_payload["manifest_bytes"] == len(manifest_bytes)
    assert target_payload["manifest_sha256"] == hashlib.sha256(manifest_bytes).hexdigest()
    assert summary_payload["checksum_path"] == str(checksums)
    checksum_lines = checksums.read_text(encoding="utf-8").splitlines()
    assert f"{hashlib.sha256(manifest_bytes).hexdigest()}  k3s-research.yaml" in checksum_lines
    assert (
        f"{hashlib.sha256(target_report_bytes).hexdigest()}  k3s-research.dry-run.json"
        in checksum_lines
    )
    assert f"{hashlib.sha256(summary_bytes).hexdigest()}  summary.json" in checksum_lines
    assert not any(line.endswith("checksums.txt") for line in checksum_lines)


def test_kubernetes_dry_run_artifact_records_proof_command(tmp_path: Path) -> None:
    from agmind.services.kubernetes_dry_run import (
        CommandResult,
        run_kubernetes_server_dry_run,
    )

    def fake_runner(command: tuple[str, ...], manifest: Path) -> CommandResult:
        if command[-4:] == ("get", "nodes", "-o", "json"):
            return CommandResult(
                returncode=0,
                stdout=json.dumps(
                    {
                        "items": [
                            {
                                "metadata": {"name": "strix"},
                                "status": {"allocatable": {"amd.com/gpu": "1"}},
                            }
                        ]
                    }
                ),
                stderr="",
            )
        return CommandResult(returncode=0, stdout="server dry-run ok", stderr="")

    report = run_kubernetes_server_dry_run(
        {"k3s-research": _kubernetes_target()},
        kubectl="kubectl",
        kube_context="strix-k3s",
        namespace="agmind-ci",
        require_cluster=True,
        require_amd_gpu=True,
        target_ids=("k3s-research",),
        runner=fake_runner,
        artifact_dir=tmp_path,
    )

    proof_command = tmp_path / "proof-command.txt"
    expected_command = [
        "scripts/kubernetes_dry_run.py",
        "--target",
        "k3s-research",
        "--require-cluster",
        "--require-amd-gpu",
        "--artifact-dir",
        str(tmp_path),
        "--namespace",
        "agmind-ci",
        "--kubectl",
        "kubectl",
        "--context",
        "strix-k3s",
    ]
    summary_payload = json.loads((tmp_path / "summary.json").read_text(encoding="utf-8"))
    proof_command_bytes = proof_command.read_bytes()
    checksum_lines = (tmp_path / "checksums.txt").read_text(encoding="utf-8").splitlines()

    assert report.ok is True
    assert proof_command.read_text(encoding="utf-8").strip() == " ".join(expected_command)
    assert summary_payload["proof_command"] == expected_command
    assert summary_payload["proof_command_path"] == str(proof_command)
    assert f"{hashlib.sha256(proof_command_bytes).hexdigest()}  proof-command.txt" in checksum_lines


