def test_kubernetes_dry_run_runs_kubectl_with_rendered_manifest() -> None:
    from agmind.services.kubernetes_dry_run import (
        CommandResult,
        run_kubernetes_server_dry_run,
    )

    calls: list[tuple[tuple[str, ...], str]] = []

    def fake_runner(command: tuple[str, ...], manifest: Path) -> CommandResult:
        calls.append((command, manifest.read_text(encoding="utf-8")))
        return CommandResult(returncode=0, stdout="server dry-run ok", stderr="")

    report = run_kubernetes_server_dry_run(
        {"k3s-research": _kubernetes_target()},
        kubectl="kubectl",
        runner=fake_runner,
    )

    assert report.ok is True
    assert report.targets[0].status == "passed"
    assert report.targets[0].returncode == 0
    assert report.targets[0].stdout == "server dry-run ok"
    assert calls
    command, manifest_text = calls[0]
    assert command[:4] == ("kubectl", "apply", "--dry-run=server", "-f")
    assert manifest_text.startswith("# Auto-generated by `agmind render kubernetes`")
    payload = report.to_json()
    assert payload["ok"] is True
    target_payload = payload["targets"][0]
    assert target_payload["target_id"] == "k3s-research"
    assert target_payload["status"] == "passed"
    assert target_payload["command"][:4] == ["kubectl", "apply", "--dry-run=server", "-f"]
    assert target_payload["warning_summary"] == {"info": 0, "warning": 0, "blocker": 0}
    assert target_payload["warnings"] == []
    assert target_payload["stdout"] == "server dry-run ok"
    assert target_payload["stderr"] == ""


